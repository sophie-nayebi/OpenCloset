/// Unsupported platform handling
/// Returns the fallback path for platforms that are not officially supported

/// Gets the path for categories CSV file
String getCategoriesPath() {
  return '/unsupported/categories.csv';
}

/// Gets the path for items CSV file
String getItemsPath() {
  return '/unsupported/items.csv';
}

/// Gets the path for outfits CSV file
String getOutfitsPath() {
  return '/unsupported/outfits.csv';
}

/// Gets the path for outfit_items CSV file
String getOutfitItemsPath() {
  return '/unsupported/outfit_items.csv';
}
